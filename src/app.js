const express = require('express');
const helmet = require('helmet');
const cors = require('cors');
const morgan = require('morgan');
const path = require('path');
const rateLimit = require('express-rate-limit');
const { errorHandler } = require('./middleware');
const app = express();

app.set('trust proxy', 1);
app.use(helmet({ crossOriginResourcePolicy: { policy: 'cross-origin' } }));
app.use(cors({ origin: (process.env.CLIENT_URL || 'http://localhost:4200').split(',').map((s) => s.trim()), credentials: true }));
app.use(express.json({ limit: '1mb' }));
if (process.env.NODE_ENV !== 'test') app.use(morgan('dev'));
app.use('/uploads', express.static(path.join(__dirname, '../uploads'), { setHeaders: (r) => r.set('X-Content-Type-Options', 'nosniff') }));
app.get('/api/health', (req, res) => res.json({ ok: true }));
app.use('/api/auth', rateLimit({ windowMs: 15 * 60 * 1000, limit: 100 }), require('./routes/auth'));
app.use('/api/admin', require('./routes/admin'));
app.use('/api', rateLimit({ windowMs: 60 * 1000, limit: 300 }), require('./routes/user'));
app.use((req, res) => res.status(404).json({ message: 'Not found' }));
app.use(errorHandler);
module.exports = app;
